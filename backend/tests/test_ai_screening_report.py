@pytest.mark.asyncio
async def test_saved_prediction_pdf(database):
    rows,calls=database
    data=await report_service.get_ai_screening_pdf('screen','clinic')
    reader=fitz.open(stream=data, filetype='pdf'); text='\n'.join(p.get_text() for p in reader)
    for expected in ['Report Test Patient','TEST-42','Moderate Diabetic Retinopathy','80.0%','AI-prediction','IMPORTANT DISCLAIMER','AI Attention / Grad-CAM Visualization']:
        assert expected in text
    assert calls == [('fundus-images','clinic/image.png'),('gradcam-heatmaps','clinic/image/cam.png')]
    assert sum(len(page.get_image_info()) for page in reader)>=2
    normalized = ' '.join(text.split())
    assert 'NETRAVA AI Screening Report' in normalized
    assert ('This result is generated by an AI screening system and is intended to support screening '
            'and clinical decision-making. It is not a final medical diagnosis. A qualified healthcare '
            'professional should review the retinal images and findings before making a diagnosis '
            'or treatment decision.') in normalized
    assert '2026-11-15' in normalized
    for value in ['5.00%', '80.00%']:
        assert value in normalized

