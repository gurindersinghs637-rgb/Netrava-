import 'dart:typed_data';
import 'package:flutter/material.dart';
import '../../providers/session.dart';
import '../../core/network/api_client.dart';
import '../../services/pdf_files.dart';
import '../../widgets/clinical_widgets.dart';

/// AI screening support report, independent of clinician review.
class AiReportScreen extends StatefulWidget {
  final Session session;
  final String screeningId;
  final String? predictionId;
  final bool generateOnOpen;
  final PdfFiles? files;
  const AiReportScreen({
    super.key,
    required this.session,
    required this.screeningId,
    this.predictionId,
    this.generateOnOpen = false,
    this.files,
  });
  @override
  State<AiReportScreen> createState() => _AiReportScreenState();
}

class _AiReportScreenState extends State<AiReportScreen> {
  Uint8List? _pdf;
  bool _busy = false;
  bool _opening = false;
  String? _error, _message, _owner;

  @override
  void initState() {
    super.initState();
    if (widget.generateOnOpen) {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (mounted) _generate();
      });
    }
  }

  Future<void> _generate() async {
    if (_busy) return;
    final owner = widget.session.user?.id;
    setState(() {
      _busy = true;
      _error = null;
      _message = null;
    });
    try {
      final bytes = await widget.session.reports.aiPdf(
        widget.screeningId,
        predictionId: widget.predictionId,
      );
      if (bytes.length < 5 || String.fromCharCodes(bytes.take(5)) != '%PDF-') {
        throw const FormatException('Invalid PDF response');
      }
      if (mounted && owner != null && widget.session.user?.id == owner) {
        setState(() {
          _pdf = bytes;
          _owner = owner;
          _message = 'AI Screening Report Ready';
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() => _error = _generationError(e));
      }
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  String _generationError(Object error) {
    if (error is! ApiFailure) {
      return 'We could not generate the report. Please try again.';
    }
    if (error.status == 401) {
      return 'Your session has expired. Please log in again.';
    }
    if (error.status == 403) {
      return 'You do not have permission to access this screening report.';
    }
    if (error.status == 404) {
      return 'The screening result could not be found in your workspace.';
    }
    if (error.status == null) {
      return 'Unable to connect to the NETRAVA server. Check your connection and try again.';
    }
    return error.message;
  }

  Future<void> _open() async {
    if (_busy ||
        _pdf == null ||
        _owner == null ||
        widget.session.user?.id != _owner) {
      return;
    }
    setState(() {
      _busy = true;
      _opening = true;
      _error = null;
    });
    try {
      final message = await (widget.files ?? PdfFiles.instance).saveAndOpen(
        'ai-${widget.screeningId}-${widget.predictionId ?? 'latest'}',
        _pdf!,
      );
      if (mounted) setState(() => _message = message);
    } catch (_) {
      if (mounted) {
        setState(
          () => _error =
              'The report was generated successfully, but it could not be opened on this device. Check your PDF viewer and try again.',
        );
      }
    } finally {
      if (mounted) {
        setState(() {
          _busy = false;
          _opening = false;
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) => Scaffold(
    appBar: AppBar(title: const Text('NETRAVA AI Screening Report')),
    body: PageBody(
      children: [
        const SectionHeading(
          'AI screening support report',
          subtitle:
              'This result is generated by an AI screening system and is not a final medical diagnosis.',
        ),
        ClinicalDataRow('Screening ID', widget.screeningId),
        if (widget.predictionId != null)
          ClinicalDataRow('Prediction ID', widget.predictionId),
        PrimaryAction(
          'Generate Report',
          busy: _busy,
          onPressed: _generate,
          icon: Icons.picture_as_pdf_outlined,
        ),
        ErrorNotice(_error),
        if (_busy)
          Text(
            _opening
                ? 'Opening your report...'
                : 'Generating your AI Screening Report...',
          ),
        if (_message != null) Text(_message!),
        if (_pdf != null) ...[
          TextButton.icon(
            onPressed: _busy ? null : _open,
            icon: const Icon(Icons.visibility),
            label: const Text('View Report'),
          ),
          OutlinedButton.icon(
            onPressed: _busy ? null : _open,
            icon: const Icon(Icons.download),
            label: const Text('Download/Open Report'),
          ),
          const Text(
            'The PDF is saved in private app storage and opened with your device PDF viewer. Local reports are cleared on logout.',
          ),
        ],
        const SizedBox(height: 20),
        const Text(clinicalDisclaimer),
      ],
    ),
  );
}
